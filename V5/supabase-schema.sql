create table if not exists public.projects (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users(id) on delete cascade default auth.uid(),
    name text not null,
    due_date date,
    priority text check (priority in ('high', 'medium', 'low') or priority is null),
    created_at timestamptz not null default now()
);

create table if not exists public.subjects (
    id bigint generated by default as identity primary key,
    name text not null,
    project_id bigint references public.projects(id) on delete cascade,
    due_date date,
    priority text check (priority in ('high', 'medium', 'low') or priority is null),
    created_at timestamptz not null default now()
);

create table if not exists public.notes (
    id bigint generated by default as identity primary key,
    subject_id bigint references public.subjects(id) on delete cascade,
    stuff text not null,
    due_date date,
    priority text check (priority in ('high', 'medium', 'low') or priority is null),
    created_at timestamptz not null default now()
);

alter table public.projects
    add column if not exists user_id uuid references auth.users(id) on delete cascade;

alter table public.projects
    alter column user_id set default auth.uid();

create index if not exists projects_user_id_idx on public.projects(user_id);
create index if not exists subjects_project_id_idx on public.subjects(project_id);
create index if not exists notes_subject_id_idx on public.notes(subject_id);


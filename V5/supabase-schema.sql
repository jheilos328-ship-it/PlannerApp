create policy "planner user select projects" on public.projects
for select to authenticated
using (user_id = auth.uid());

create policy "planner user insert projects" on public.projects
for insert to authenticated
with check (user_id = auth.uid());

create policy "planner user update projects" on public.projects
for update to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

create policy "planner user delete projects" on public.projects
for delete to authenticated
using (user_id = auth.uid());

create policy "planner user select subjects" on public.subjects
for select to authenticated
using (
    exists (
        select 1
        from public.projects p
        where p.id = subjects.project_id
          and p.user_id = auth.uid()
    )
);

